/** The mark for a provider id, or null when we have no glyph for it.
 *
 *  Matched on a prefix so the variants a driver registers — `slack_webhook`,
 *  `discord_webhook`, `zulip_webhook` — resolve to their brand rather than to
 *  nothing. Longest key first, so a future `github_enterprise` could take its
 *  own mark without `github` swallowing it. */
function markFor(provider: string): string | null {
  const id = provider.toLowerCase();
  const key = Object.keys(MARKS)
    .sort((a, b) => b.length - a.length)
    .find((k) => id.startsWith(k) || id.includes(k));
  return key ? MARKS[key] : null;
}

/** A provider's logo at `size`, or a lettered disc when there is no glyph.
 *
 *  The fallback is not decoration: a driver plugin can register a provider
 *  this file has never heard of, and an empty cell where every other row has
 *  a mark reads as a broken image rather than as "no logo for this one". */
export function ConnectorLogo({
  provider,
  label,
  size = 18,
}: {
  provider: string;
  /** Display name, used for the fallback letter and the accessible title. */
  label?: string;
  size?: number;
}): ReactNode {
  const d = markFor(provider);
  const title = label || provider;
  if (!d) {
    return (
      <span className="conn-logo conn-logo-fallback" style={{ width: size, height: size }} title={title}>
        {(title.trim()[0] ?? "?").toUpperCase()}
      </span>
    );
  }
  return (
    <svg
      className="conn-logo"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      role="img"
      aria-label={title}
    >
      <title>{title}</title>
      <path d={d} />
    </svg>
  );
}
